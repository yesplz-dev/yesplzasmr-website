  const form = document.getElementById('bookingForm');
  const formStatus = document.getElementById('formStatus');
  const submitBtn = form.querySelector('.submit-btn');

  form.addEventListener('submit', function(e){
    e.preventDefault();

    const tierSelect = document.getElementById('tier');
    const tierDisplayText = tierSelect.options[tierSelect.selectedIndex].text; // translated label, for the customer-facing auto-reply

    const payload = {
      name: document.getElementById('name').value,
      business: document.getElementById('business').value,
      email: document.getElementById('email').value,
      city: document.getElementById('city').value,
      tier: tierSelect.value,
      message: document.getElementById('message').value
    };

    const originalLabel = translations['form.submit'][currentLang];
    submitBtn.disabled = true;
    submitBtn.textContent = translations['form.sending'][currentLang];
    formStatus.className = 'form-status';
    formStatus.textContent = '';

    const notifyBusiness = emailjs.send(EMAILJS_SERVICE_ID, EMAILJS_TEMPLATE_ID, payload);
    const autoReply = emailjs.send(EMAILJS_SERVICE_ID, EMAILJS_AUTOREPLY_TEMPLATE_ID, {
      name: payload.name,
      email: payload.email,
      title: tierDisplayText
    });

    Promise.all([notifyBusiness, autoReply])
      .then(() => {
        formStatus.textContent = translations['form.success'][currentLang];
        formStatus.classList.add('is-success');
        form.reset();
      })
      .catch(() => {
        formStatus.textContent = translations['form.error'][currentLang];
        formStatus.classList.add('is-error');
      })
      .finally(() => {
        submitBtn.disabled = false;
        submitBtn.textContent = originalLabel;
      });
  });

